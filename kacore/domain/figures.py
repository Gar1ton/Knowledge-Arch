"""PDF 图表空位（纯数据模型，零依赖）。

为什么存在：PyMuPDF4LLM 抽正文时把图整个丢掉。上传时在本地按 PDF 结构找出每张图，存一个「空位」：
位置、标题、图内文字；开了识图再由模型补描述。图的截图不落盘，需要时按位置从原 PDF 现渲染。

契约：
- `page` 从 1 起；`bbox` 是该页 PDF 坐标（点，左上原点）的 `(x0, y0, x1, y1)`。
- `figure_id` 在文档内稳定：`<doc_id>_fig<页>_<页内序号>`，序号按版面自上而下、自左而右。
- 重新抽取时按 `match_key`（页 + 取整后的位置）把旧描述接到新空位上，不重复调用模型。
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace

# ── 状态常量 ──────────────────────────────────────────────────
FIGURE_PENDING = "pending"  # 已找到，尚未描述
FIGURE_DONE = "done"  # 已有模型描述
FIGURE_FAILED = "failed"  # 描述失败（error 记原因），下次「仅补缺失」会重试
FIGURE_SKIPPED = "skipped"  # 不值得描述（如过小、重复），不再重试
FIGURE_STATUSES = frozenset({FIGURE_PENDING, FIGURE_DONE, FIGURE_FAILED, FIGURE_SKIPPED})
# 「补全图表描述（仅缺失）」要处理的状态。
FIGURE_MISSING_STATUSES = frozenset({FIGURE_PENDING, FIGURE_FAILED})

KIND_RASTER = "raster"  # 位图
KIND_VECTOR = "vector"  # 矢量绘图（图表、流程图）
KIND_MIXED = "mixed"  # 位图与矢量拼成的一张图

# chunk 的 metadata["chunk_kind"]：正文块与图块。图块不在 clean.md 上，没有正文字符偏移。
CHUNK_KIND_BODY = "body"
CHUNK_KIND_FIGURE = "figure"
# 图块里图内文字的上限：流程图 / 示例图可能有上千字，全塞进去会冲淡标题与描述。
_INNER_TEXT_CHUNK_CHARS = 1500

# 位置取整粒度（点）：同一 PDF 重新抽取时 bbox 有浮点抖动，取整后才能稳定匹配。
_MATCH_GRID = 4.0

BBox = tuple[float, float, float, float]


@dataclass
class DocumentFigure:
    """一张图的空位与（可选的）模型描述。"""

    figure_id: str
    doc_id: str
    page: int
    ordinal: int
    bbox: BBox
    kind: str = KIND_VECTOR
    label: str = ""  # 如 "Figure 3"；没有配上标题时为空
    caption: str = ""  # 标题全文
    inner_text: str = ""  # 图区域内的文字（坐标刻度、图例、方框文字），从正文挪过来
    status: str = FIGURE_PENDING
    description: str = ""
    model: str = ""
    prompt_version: str = ""
    image_hash: str = ""
    error: str = ""
    updated_at: str = ""
    meta: dict[str, object] = field(default_factory=dict)

    @property
    def match_key(self) -> tuple[int, int, int, int, int]:
        x0, y0, x1, y1 = (round(v / _MATCH_GRID) for v in self.bbox)
        return (self.page, x0, y0, x1, y1)


def figure_chunk_text(fig: DocumentFigure) -> str:
    """图块正文：`Figure 3 (page 5)` + 标题 + 模型描述 + 图内文字。三者都空时返回空串（不建块）。"""
    caption = fig.caption.strip()
    description = fig.description.strip()
    inner = " · ".join(line.strip() for line in fig.inner_text.splitlines() if line.strip())
    if not (caption or description or inner):
        return ""
    if len(inner) > _INNER_TEXT_CHUNK_CHARS:
        inner = inner[:_INNER_TEXT_CHUNK_CHARS].rstrip() + " …"
    parts = [f"{fig.label or 'Figure'} (page {fig.page})"]
    if caption:
        parts.append(caption)
    if description:
        # 写明出处：回答模型据此知道这段是识图模型的转述，不是论文原文。
        parts.append(f"Figure description (generated by a vision model): {description}")
    if inner:
        parts.append(f"Text in figure: {inner}")
    return "\n\n".join(parts)


def is_figure_chunk(metadata: dict[str, object]) -> bool:
    return metadata.get("chunk_kind") == CHUNK_KIND_FIGURE


def figure_id_for(doc_id: str, page: int, ordinal: int) -> str:
    return f"{doc_id}_fig{page:03d}_{ordinal:02d}"


def merge_figure_descriptions(
    fresh: list[DocumentFigure], previous: list[DocumentFigure]
) -> list[DocumentFigure]:
    """新检测结果接上旧描述：位置相同的空位保留旧的状态、描述、模型与图片哈希。

    新空位的标题、图内文字以本次检测为准；旧的 skipped 也保留（用户或规则已决定不描述）。
    没有匹配上的旧空位随文档版本一起丢弃。
    """
    old_by_key = {fig.match_key: fig for fig in previous}
    merged: list[DocumentFigure] = []
    for fig in fresh:
        old = old_by_key.get(fig.match_key)
        if old is None or old.status == FIGURE_PENDING:
            merged.append(fig)
            continue
        merged.append(replace(
            fig,
            status=old.status,
            description=old.description,
            model=old.model,
            prompt_version=old.prompt_version,
            image_hash=old.image_hash,
            error=old.error,
            updated_at=old.updated_at,
        ))
    return merged


